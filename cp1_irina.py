import ee
import google.colab
import google.auth
import pandas as pd
import numpy as np
from sklearn.preprocessing import StandardScaler

# 1. AUTENTIFICARE ȘI INIȚIALIZARE GEE
google.colab.auth.authenticate_user()
credentials, _ = google.auth.default()

# Folosim ID-ul proiectului tău validat anterior
try:
    ee.Initialize(credentials, project='project-2cd48704-b05c-4ce8-9f5')
    print("Conexiune GEE activă.")
except Exception as e:
    print(f"Eroare GEE: {e}")

# 2. EXTRAGERE DATE SATELIT (MODIS NDVI) PE JUDEȚE
print("Se extrag datele din Google Earth Engine...")
judete_fc = ee.FeatureCollection("FAO/GAUL/2015/level1") \
              .filter(ee.Filter.eq('ADM0_NAME', 'Romania'))

ani = [2021, 2022] # Am pus doar 2 ani pentru ca rularea sa fie rapida
luni = [4, 5, 6, 7, 8, 9]

corine = ee.Image('COPERNICUS/CORINE/V20/100m/2018').select('landcover')
masca_arabil = corine.gte(211).And(corine.lte(213))
modis_col = ee.ImageCollection("MODIS/061/MOD13Q1")

def extrage_lunar(an, luna):
    start_date = ee.Date.fromYMD(an, luna, 1)
    end_date = start_date.advance(1, 'month')
    img_luna = modis_col.filterDate(start_date, end_date)

    def clean_ndvi(img):
        qa = img.select('SummaryQA')
        return img.select('NDVI').updateMask(qa.lte(1))

    ndvi_lunar = img_luna.map(clean_ndvi).median().updateMask(masca_arabil)
    stats = ndvi_lunar.reduceRegions(collection=judete_fc, reducer=ee.Reducer.mean(), scale=1000)

    def formateaza(f):
        return f.set({'an': an, 'luna': luna, 'ndvi_mean': ee.Number(f.get('mean')).multiply(0.0001)})
    return stats.map(formateaza)

rezultate_ndvi = []
for an in ani:
    fc_an = ee.FeatureCollection([])
    for luna in luni:
        fc_an = fc_an.merge(extrage_lunar(an, luna))

    date_an = fc_an.reduceColumns(
        reducer=ee.Reducer.toList(4),
        selectors=['ADM1_NAME', 'an', 'luna', 'ndvi_mean']
    ).getInfo()['list']
    rezultate_ndvi.extend(date_an)

df_ndvi = pd.DataFrame(rezultate_ndvi, columns=['judet', 'an', 'luna', 'ndvi_mean'])
df_ndvi['judet'] = df_ndvi['judet'].str.upper().str.strip()

# 3. PREGĂTIRE SURSE AUXILIARE (Simulare SPEI și INS pentru a nu bloca fluxul)
df_spei = df_ndvi[['judet', 'an', 'luna']].copy()
np.random.seed(42)
df_spei['spei_1m'] = np.random.normal(0.0, 1.0, size=len(df_spei))
df_spei['spei_3m'] = np.random.normal(0.0, 1.0, size=len(df_spei))

judete_unice = df_ndvi['judet'].unique()
df_ins = pd.DataFrame([(j, a) for j in judete_unice for a in ani], columns=['judet', 'an'])
df_ins['randament_grau'] = np.random.normal(3800, 700, size=len(df_ins))

# 4. ALINIERE (Join-uri)
df_aliniat = pd.merge(df_ndvi, df_spei, on=['judet', 'an', 'luna'], how='inner')
df_aliniat = pd.merge(df_aliniat, df_ins, on=['judet', 'an'], how='left')

# 5. SCALARE (Generarea Matricei X conform CP1)
trasaturi = ['ndvi_mean', 'spei_1m', 'spei_3m', 'randament_grau']
scaler = StandardScaler()
df_aliniat[trasaturi] = scaler.fit_transform(df_aliniat[trasaturi])

# 6. RAPORT ȘI SALVARE
print("=" * 60)
print("RAPORT DE ACOPERIRE ȘI MATRICEA X (PENTRU SLIDE 2):")
print(f"Total observații aliniate spațio-temporal: {len(df_aliniat)}")
print(f"Valori lipsă: \n{df_aliniat.isna().sum()}")
print("=" * 60)
print("\nPrimele rânduri din Matricea X (scalată):")
print(df_aliniat.head())

df_aliniat.to_csv("Matricea_X_CP1_Popa_Irina.csv", index=False)
print("\nFișierul 'Matricea_X_CP1_Popa_Irina.csv' a fost salvat!")